'use client';

import { useSetAtom } from 'jotai';
import { Lock, Pencil, PencilLine, Plus, Users } from 'lucide-react';
import dynamic from 'next/dynamic';
import Link from 'next/link';
import { usePathname, useSearchParams } from 'next/navigation';
import { posthog } from 'posthog-js';
import {
  type ReactNode,
  useCallback,
  useEffect,
  useMemo,
  useRef,
  useState,
} from 'react';

import BiListUl from '@/components/icons/BiListUl';
import type { IconType } from '@/components/icons/helpers/GenIcon';
import MdList from '@/components/icons/MdList';
import MdOutlineChatBubbleOutline from '@/components/icons/MdOutlineChatBubbleOutline';
import RiUserSettingsLine from '@/components/icons/RiUserSettingsLine';
import { Button } from '@/components/ui/button';
import {
  DropdownMenu,
  DropdownMenuContent,
  DropdownMenuItem,
  DropdownMenuTrigger,
} from '@/components/ui/dropdown-menu';
import { Tooltip } from '@/components/ui/tooltip';
import { JTTG } from '@/constants/Telegram';
import { useDisclosure } from '@/hooks/use-disclosure';
import { useViewer } from '@/lib/viewer';
import type { HackathonModel } from '@/prisma/models/Hackathon';
import type { ActiveHackathon } from '@/server/sponsor-dashboard';
import Sparkle from '@/svg/sparkle';
import { cn } from '@/utils/cn';

import { isAutoGenerateOpenAtom } from '@/features/listing-builder/atoms';

import { NavItem } from './NavItems';
import { SelectHackathon } from './SelectHackathon';
import { SelectSponsor } from './SelectSponsor';

// The sponsors area's modal; mounted only when it shows.
const EntityNameModal = dynamic(() =>
  import('@/components/modals/EntityNameModal').then((m) => m.EntityNameModal),
);

// The listing builder's dialog; mounted only once asked for.
const AutoGenerateDialog = dynamic(() =>
  import('@/features/listing-builder/components/AutoGenerate/Dialog').then(
    (m) => m.AutoGenerateDialog,
  ),
);

const CreateListingModal = dynamic(() =>
  import('./CreateListingModal').then((m) => m.CreateListingModal),
);

const SponsorInfoModal = dynamic(() =>
  import('./SponsorInfoModal').then((m) => m.SponsorInfoModal),
);

interface LinkItemProps {
  name: string;
  link?: string;
  icon: IconType;
  isExternal?: boolean;
  posthog?: string;
}

// The sponsor dashboard's sidebar around a page, as Earn's SponsorLayout drew
// it. The viewer is signed in with a sponsor (src/layouts/Sponsor.tsx sees
// to that).
export function SponsorFrame({
  children,
  isCollapsible = false,
  hackathons,
  isCreateListingAllowed,
}: {
  children: ReactNode;
  isCollapsible?: boolean;
  hackathons: ReadonlyArray<ActiveHackathon>;
  isCreateListingAllowed: boolean;
}) {
  const user = useViewer();
  const pathname = usePathname() ?? '';
  const searchParams = useSearchParams();
  const { isOpen, onOpen, onClose } = useDisclosure();

  const [isExpanded, setIsExpanded] = useState(() => !isCollapsible);
  const timeoutRef = useRef<NodeJS.Timeout | null>(null);
  const canSelectSponsor =
    user?.role === 'GOD' || (user?.UserSponsors?.length ?? 0) > 0;

  const open = !!searchParams?.get('open');
  const [isAutoGenerateMounted, setIsAutoGenerateMounted] = useState(open);
  const setAutoGenerateOpen = useSetAtom(isAutoGenerateOpenAtom);
  const openAutoGenerate = useCallback(() => {
    setIsAutoGenerateMounted(true);
    setAutoGenerateOpen(true);
  }, [setAutoGenerateOpen]);

  const handleMouseEnter = useCallback(() => {
    if (!isCollapsible) return;
    if (timeoutRef.current) {
      clearTimeout(timeoutRef.current);
    }
    timeoutRef.current = setTimeout(() => {
      setIsExpanded(true);
    }, 250);
  }, [isCollapsible]);

  const handleMouseLeave = useCallback(() => {
    if (!isCollapsible) return;
    if (timeoutRef.current) {
      clearTimeout(timeoutRef.current);
    }
    setIsExpanded(false);
  }, [isCollapsible]);

  useEffect(() => {
    if (open) setAutoGenerateOpen(true);
  }, [open, setAutoGenerateOpen]);

  // Earn asks for their own details first, then for the sponsor's entity
  // name; each goes away once saved (the viewer reloads).
  const [isSponsorInfoDismissed, setIsSponsorInfoDismissed] = useState(false);
  const [isEntityDismissed, setIsEntityDismissed] = useState(false);
  const needsSponsorInfo =
    !!user?.currentSponsorId &&
    (!user?.firstName || !user?.lastName || !user?.username || !user?.telegram);
  const isSponsorInfoModalOpen = needsSponsorInfo && !isSponsorInfoDismissed;
  const isEntityModalOpen =
    !needsSponsorInfo &&
    !user?.currentSponsor?.entityName &&
    user?.role !== 'GOD' &&
    !isEntityDismissed;
  const onSponsorInfoModalClose = () => setIsSponsorInfoDismissed(true);
  const handleEntityClose = () => setIsEntityDismissed(true);

  const isHackathonRoute = useMemo(
    () => pathname.startsWith('/earn/dashboard/hackathon'),
    [pathname],
  );

  const isLocalProfileVisible = useMemo(() => {
    const sponsorChapterId = user?.currentSponsor?.chapter?.id;
    if (!sponsorChapterId) return false;
    if (user?.role === 'GOD') return true;
    const isCoreMember = user?.people?.type?.toUpperCase() === 'CORE';
    return isCoreMember && user?.people?.chapterId === sponsorChapterId;
  }, [
    user?.currentSponsor?.chapter?.id,
    user?.people?.chapterId,
    user?.people?.type,
    user?.role,
  ]);

  // The builder's and the create modal's type; dates survive the trip.
  // oxlint-disable-next-line typescript/no-unsafe-type-assertion
  const hackathonModels = hackathons as unknown as HackathonModel[];

  const LinkItems: Array<LinkItemProps> = isHackathonRoute
    ? [
        {
          name: 'All Tracks',
          link: `/hackathon`,
          icon: MdList,
        },
        {
          name: 'Get Help',
          link: JTTG,
          icon: MdOutlineChatBubbleOutline,
          posthog: 'get help_sponsor',
        },
      ]
    : [
        {
          name: 'My Listings',
          link: '/listings',
          icon: BiListUl,
        },
        {
          name: 'Team Settings',
          link: '/team-settings',
          icon: RiUserSettingsLine,
        },
        ...(isLocalProfileVisible
          ? [
              {
                name: 'Local Profiles',
                link: '/local-profiles',
                icon: Users,
              },
            ]
          : []),
        {
          name: 'Edit Profile',
          link: '/sponsor/edit',
          icon: Pencil,
        },
        {
          name: 'FAQ',
          link: '/faq',
          icon: MdOutlineChatBubbleOutline,
          posthog: 'faq_sponsor',
        },
      ];

  const showContent = isHackathonRoute
    ? user?.hackathonId || user?.role === 'GOD'
    : user?.currentSponsor?.id;

  const isCreateLocked = !isCreateListingAllowed && user?.role !== 'GOD';

  return (
    <>
      {isSponsorInfoModalOpen && (
        <SponsorInfoModal
          onClose={onSponsorInfoModalClose}
          isOpen={isSponsorInfoModalOpen}
        />
      )}

      {isEntityModalOpen && (
        <EntityNameModal
          isOpen={isEntityModalOpen}
          onClose={handleEntityClose}
        />
      )}

      <div className="flex min-h-[80vh] px-3 md:hidden">
        <p className="pt-20 text-center text-xl font-medium text-slate-500">
          The Sponsor Dashboard on Earn is not optimized for mobile yet. Please
          use a desktop to check out the Sponsor Dashboard
        </p>
      </div>
      <div className="hidden min-h-[max(100vh,1000px)] justify-start transition-all duration-300 ease-in-out hover:shadow-lg md:flex">
        <div
          className={cn(
            'sponsor-dashboard-sidebar overflow-x-hidden border-r border-slate-200 bg-white pt-5 whitespace-nowrap',
            'transition-all duration-300 ease-in-out',
            'transition-shadow hover:shadow-lg',
            isCollapsible ? 'fixed' : 'static',
            isExpanded
              ? ['w-64 max-w-64 min-w-64', 'expanded']
              : ['w-20 max-w-20 min-w-20'],
            'top-12 bottom-0 left-0 z-10',
          )}
          onMouseEnter={handleMouseEnter}
          onMouseLeave={handleMouseLeave}
        >
          {canSelectSponsor && (
            <div className={cn('pb-6', isExpanded ? 'pr-4 pl-6' : 'px-4')}>
              {isHackathonRoute ? (
                <SelectHackathon isExpanded={isExpanded} />
              ) : (
                <SelectSponsor isExpanded={isExpanded} />
              )}
            </div>
          )}
          {isOpen && (
            <CreateListingModal
              isOpen={isOpen}
              onClose={onClose}
              hackathons={hackathons}
            />
          )}
          {isAutoGenerateMounted && (
            <AutoGenerateDialog hackathons={hackathonModels} />
          )}
          <div
            className={cn(
              'flex items-center justify-between px-4 pb-6',
              isExpanded ? 'pr-4 pl-6' : 'px-4',
            )}
          >
            {!isHackathonRoute ? (
              <DropdownMenu>
                <Tooltip
                  content={
                    "Creating a new listing has been temporarily locked for you since you have 5 listings which are 'In Review'. Please announce the winners for such listings to create new listings."
                  }
                  disabled={!isCreateLocked}
                >
                  <DropdownMenuTrigger asChild>
                    <Button
                      className={cn(
                        'ph-no-capture w-full gap-2 py-5.5 text-base',
                        'disabled:cursor-not-allowed disabled:opacity-50',
                      )}
                      disabled={isCreateLocked}
                      variant="default"
                    >
                      <Plus className="h-3 w-3" />
                      <p
                        className={cn(
                          'nav-item-text transition-all duration-200 ease-in-out',
                          isExpanded
                            ? ['static ml-0 opacity-100']
                            : ['absolute -ml-[9999px] opacity-0'],
                        )}
                      >
                        <span>Create New Listing</span>
                      </p>
                      {isCreateLocked && <Lock className="h-4 w-4" />}
                    </Button>
                  </DropdownMenuTrigger>
                  <DropdownMenuContent
                    className="min-w-[200px] font-medium text-slate-500"
                    align="start"
                  >
                    <DropdownMenuItem
                      className="flex items-center justify-between"
                      onClick={() => {
                        posthog.capture('new generate with ai_sponsor');
                        openAutoGenerate();
                      }}
                    >
                      <span className="flex items-center gap-2 text-sm">
                        <Sparkle className="h-4 w-4" />
                        Generate with AI
                      </span>
                      <span>
                        <span className="rounded-full bg-emerald-50 px-1.5 py-0.5 text-[0.65rem] text-emerald-600">
                          2m
                        </span>
                      </span>
                    </DropdownMenuItem>
                    <DropdownMenuItem
                      className="flex items-center justify-between"
                      onClick={() => {
                        posthog.capture('new start from scratch_sponsor');
                        onOpen();
                      }}
                    >
                      <span className="flex items-center gap-2 text-sm">
                        <PencilLine className="h-4 w-4" />
                        Start from Scratch
                      </span>
                      <span>
                        <span className="rounded-full bg-indigo-50 px-1.5 py-0.5 text-[0.65rem] text-indigo-600">
                          10m
                        </span>
                      </span>
                    </DropdownMenuItem>
                  </DropdownMenuContent>
                </Tooltip>
              </DropdownMenu>
            ) : (
              <Button
                asChild
                className={cn('w-full gap-2 py-5.5 text-base')}
                variant="default"
              >
                <Link href="/earn/dashboard/new/?type=hackathon">
                  <Plus className="h-3 w-3" />
                  <p
                    className={cn(
                      'nav-item-text transition-opacity duration-200 ease-in-out',
                      isExpanded
                        ? ['static ml-0 opacity-100']
                        : ['absolute -ml-[9999px] opacity-0'],
                    )}
                  >
                    Create New Track
                  </p>
                </Link>
              </Button>
            )}
          </div>
          {LinkItems.map((link) => (
            <NavItem
              onClick={() => {
                if (link.posthog) posthog.capture(link.posthog);
              }}
              className="ph-no-capture"
              key={link.name}
              link={link.link}
              icon={link.icon}
              isExpanded={isExpanded}
            >
              {link.name}
            </NavItem>
          ))}
        </div>
        {showContent && (
          <div
            className={cn(
              'w-full flex-1 overflow-x-auto bg-white py-5 pr-8 pl-4 transition-[margin-left] duration-300 ease-in-out',
              isCollapsible ? 'ml-20' : 'ml-0',
            )}
          >
            {children}
          </div>
        )}
      </div>
    </>
  );
}
