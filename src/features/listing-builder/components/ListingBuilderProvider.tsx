const preventEnterKeySubmission = (e: React.KeyboardEvent<HTMLFormElement>) => {
  const target = e.target;
  if (e.key === 'Enter' && target instanceof HTMLInputElement) {
    e.preventDefault();
  }
};

function ListingEditor({
  defaultListing,
  isDuplicating,
  hackathons,
  isST,
  isGod,
  isAutoGenerated,
}: {
  defaultListing: ListingFormData;
  isDuplicating?: boolean;
  hackathons?: BuilderHackathon[];
  isST: boolean;
  isGod: boolean;
  isAutoGenerated?: boolean;
}) {
  const form = useListingForm(defaultListing, hackathons);
  const hasTriggeredInitialSaveRef = useRef(false);
  useInitAtom(
    listingStatusAtom,
    defaultListing ? listingToStatus(defaultListing) : undefined,
  );
  useInitAtom(isSTAtom, isST);
  useInitAtom(isGodAtom, isGod);
  useInitAtom(isEditingAtom, !!defaultListing.publishedAt);

  useEffect(() => {
    if (!(isDuplicating || isAutoGenerated)) return undefined;
    if (hasTriggeredInitialSaveRef.current) return undefined;
    if (form.getValues('id') || form.getValues('slug')) return undefined;

    const timerId = setTimeout(() => {
      if (form.getValues('id') || form.getValues('slug')) return;
      hasTriggeredInitialSaveRef.current = true;
      form.saveDraft();
    }, 1000);

    return () => clearTimeout(timerId);
    // oxlint-disable-next-line react/exhaustive-effect-dependencies, react-hooks/exhaustive-deps -- Earn's dependencies, kept so it runs when it did
  }, [isDuplicating, isAutoGenerated]);

  useEffect(() => {
    // keep this log, for error purposes
    // oxlint-disable-next-line no-console -- Earn logs form errors on purpose
    console.log('errors', form.formState.errors);
  }, [form.formState.errors]);

  const setConfirmModal = useSetAtom(confirmModalAtom);
  const setPreviewModal = useSetAtom(previewAtom);
  const setSubmitStatus = useSetAtom(submitStatusAtom);
  useEffect(() => {
    return () => {
      setConfirmModal(undefined);
      setPreviewModal(false);
      setSubmitStatus('idle');
    };
  }, [setConfirmModal, setPreviewModal, setSubmitStatus]);

  return (
    <>
      <div className="flex min-h-[10vh] flex-col px-3 md:hidden">
        <Header />
        <p className="w-full pt-20 text-center text-xl font-medium text-slate-500">
          The Sponsor Dashboard on Earn is not optimized for mobile yet. Please
          use a desktop to check out the Sponsor Dashboard
        </p>
      </div>
      <Form {...form}>
        <form
          onSubmit={(e) => {
            e.preventDefault();
          }}
          onKeyDown={preventEnterKeySubmission}
          className="hidden md:block"
        >
          <ListingBuilderFormLayout>
            <div className="mx-auto w-full max-w-5xl space-y-8 px-8 py-10">
              <div className="grid grid-cols-9 gap-4">
                <div className="col-span-6 space-y-4">
                  <TitleAndType />
                  <DescriptionAndTemplate />
                </div>
                <div className="sticky top-20 col-span-3 h-fit space-y-6">
                  <RewardsSheet />
                  <Deadline />
                  <WinnerAnnouncementDate />
                  <Skills />
                  <POC />
                  {/* <EligibilityQuestions /> */}
                  <EligibilityQuestionsSheet />
                </div>
              </div>
            </div>
            <ListingSuccessModal />
            <PreviewListingModal />
            <SponsorVerification />
          </ListingBuilderFormLayout>
        </form>
      </Form>
    </>
  );
}

interface Props {
  isEditing?: boolean;
  isDuplicating?: boolean;
  listing?: Omit<BuilderListing, 'id'> & { id?: string };
  hackathons?: BuilderHackathon[];
}

// atom values wont be available here, will only exist in child of HydrateAtoms immeditealy
function ListingBuilderProvider({
  isEditing = false,
  isDuplicating,
  listing,
  hackathons,
}: Props) {
  const user = useViewer();
  const isGod = user?.role === 'GOD';
  const isST = !!user?.currentSponsor?.chapter;
  const officialSuperteamRegion = getOfficialSuperteamRegion(
    user?.currentSponsor,
  );

  const generatedListing = useAtomValue(generatedListingAtom);
  const params = useSearchParams();
  const isAutoGenerated =
    params?.get('autogenerated') === 'true' && !!generatedListing;
  const hackathonSlug = params?.get('hackathon');
  const hackathonId = hackathons?.find((h) => h.slug === hackathonSlug)?.id;
  const defaultListing = listing
    ? transformListingToFormListing(listing, isST)
    : (() => {
        const defaults = getListingDefaults({
          isGod,
          isEditing,
          isST: isST,
          type: params?.get('type') === 'hackathon' ? 'hackathon' : 'bounty',
          hackathons,
          generatedListing: isAutoGenerated ? generatedListing : undefined,
          hackathonId,
        });

        defaults.region =
          officialSuperteamRegion || defaults.region || 'Global';

        return defaults;
      })();

  return (
    <Provider store={store}>
      <HydrateAtoms
        initialValues={[
          [isEditingAtom, isEditing],
          [isGodAtom, isGod],
          [isSTAtom, isST],
          [listingStatusAtom, listingToStatus(defaultListing)],
          [generatedListingAtom, generatedListing],
          [
            draftQueueAtom,
            {
              isProcessing: false,
              shouldProcessNext: false,
            },
          ],
        ]}
      >
        <ListingEditor
          defaultListing={defaultListing}
          isDuplicating={isDuplicating}
          hackathons={hackathons}
          isST={isST}
          isGod={isGod}
          isAutoGenerated={isAutoGenerated}
        />
      </HydrateAtoms>
    </Provider>
  );
}

export { ListingBuilderProvider };
